export async function saveLock(cwd: string, lock: ForkliftLock): Promise<void> {
  const validated = ForkliftLockSchema.parse(lock);
  const header = "# Auto-generated by Forklift — do not edit by hand\n";
  const content = header + YAML.stringify(validated, { lineWidth: 100 });
  await fs.writeFile(lockPath(cwd), content, "utf8");
}
